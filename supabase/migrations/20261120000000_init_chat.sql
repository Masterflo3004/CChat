-- CChat initial schema
--
-- End-to-end encryption model (see docs/E2EE.md):
--   * Every user has an X25519 key (key wrapping) and an Ed25519 key (signatures).
--     Only the PUBLIC keys are stored in plain form (profiles). The private keys are
--     stored in key_backups, encrypted client-side with a passphrase (Argon2id).
--   * Every conversation has a random symmetric key per "epoch". The key is wrapped
--     (encrypted) for each member individually and stored in conversation_keys.
--   * Messages only contain ciphertext. The server never sees plaintext, GIF URLs,
--     attachment keys or which skin/font a message uses.
--   * Any membership change creates a new epoch, so removed members cannot read new
--     messages and newly added members cannot read old ones.

-------------------------------------------------------------------------------
-- Profiles & keys
-------------------------------------------------------------------------------

create table public.profiles (
  id                  uuid primary key references auth.users on delete cascade,
  username            text not null unique
                        check (username ~ '^[a-z0-9_]{3,24}$'),
  display_name        text check (char_length(display_name) <= 64),
  x25519_public_key   text,          -- base64, set once the user creates their keys
  ed25519_public_key  text,          -- base64
  active_skin_id      uuid,          -- FK added below (message_skins)
  active_font_id      uuid,          -- FK added below (user_fonts)
  created_at          timestamptz not null default now()
);

-- Private keys, encrypted with a key derived from the user's passphrase.
create table public.key_backups (
  user_id     uuid primary key references public.profiles on delete cascade,
  kdf         jsonb not null,        -- {"alg":"argon2id","m":19456,"t":2,"p":1}
  salt        text not null,         -- base64
  nonce       text not null,         -- base64
  ciphertext  text not null,         -- base64 (ciphertext || mac)
  updated_at  timestamptz not null default now()
);

-------------------------------------------------------------------------------
-- Cosmetics: message skins (bubble textures) and custom fonts
-- These are profile cosmetics (like avatars) and are NOT end-to-end encrypted.
-- Which skin/font a given message uses IS encrypted (inside the message payload).
-------------------------------------------------------------------------------

create table public.message_skins (
  id            uuid primary key default gen_random_uuid(),
  owner_id      uuid not null references public.profiles on delete cascade,
  name          text not null check (char_length(name) between 1 and 40),
  image_path    text not null,       -- path in the "skins" bucket: <owner_id>/<file>
  fit           text not null default 'cover'
                  check (fit in ('cover', 'tile', 'stretch', 'nine_slice')),
  -- nine-slice insets in image pixels (only used when fit = 'nine_slice')
  slice_left    int not null default 0 check (slice_left >= 0),
  slice_top     int not null default 0 check (slice_top >= 0),
  slice_right   int not null default 0 check (slice_right >= 0),
  slice_bottom  int not null default 0 check (slice_bottom >= 0),
  text_color    text not null default '#FFFFFF' check (text_color ~ '^#[0-9A-Fa-f]{6}$'),
  created_at    timestamptz not null default now()
);
create index on public.message_skins (owner_id);

create table public.user_fonts (
  id          uuid primary key default gen_random_uuid(),
  owner_id    uuid not null references public.profiles on delete cascade,
  name        text not null check (char_length(name) between 1 and 40),
  file_path   text not null,         -- path in the "fonts" bucket: <owner_id>/<file>
  created_at  timestamptz not null default now()
);
create index on public.user_fonts (owner_id);

alter table public.profiles
  add constraint profiles_active_skin_fk
    foreign key (active_skin_id) references public.message_skins on delete set null,
  add constraint profiles_active_font_fk
    foreign key (active_font_id) references public.user_fonts on delete set null;

-------------------------------------------------------------------------------
-- Conversations
-------------------------------------------------------------------------------

create table public.conversations (
  id                uuid primary key,  -- generated by the client (needed to bind keys)
  is_group          boolean not null,
  name              text check (name is null or char_length(name) between 1 and 64),
  created_by        uuid references public.profiles on delete set null,
  dm_key            text unique,       -- '<smaller uuid>:<bigger uuid>' for 1:1 chats
  current_epoch     int not null default 1,
  rotation_needed   boolean not null default false,
  last_message_at   timestamptz,
  created_at        timestamptz not null default now(),
  check (is_group or dm_key is not null),
  check (not is_group or name is not null)
);

create table public.conversation_members (
  conversation_id  uuid not null references public.conversations on delete cascade,
  user_id          uuid not null references public.profiles on delete cascade,
  role             text not null default 'member' check (role in ('admin', 'member')),
  joined_at        timestamptz not null default now(),
  last_read_at     timestamptz,
  primary key (conversation_id, user_id)
);
create index on public.conversation_members (user_id);

-- One wrapped conversation key per (conversation, epoch, recipient).
create table public.conversation_keys (
  conversation_id  uuid not null references public.conversations on delete cascade,
  epoch            int not null,
  recipient_id     uuid not null references public.profiles on delete cascade,
  sender_id        uuid not null references public.profiles on delete cascade,
  wrapped_key      text not null,      -- base64 (nonce || ciphertext || mac)
  created_at       timestamptz not null default now(),
  primary key (conversation_id, epoch, recipient_id)
);
create index on public.conversation_keys (recipient_id);

create table public.messages (
  id               bigint generated always as identity primary key,
  conversation_id  uuid not null references public.conversations on delete cascade,
  sender_id        uuid not null references public.profiles on delete cascade,
  key_epoch        int not null,
  nonce            text not null,      -- base64
  ciphertext       text not null check (char_length(ciphertext) <= 65536),
  signature        text not null,      -- base64 Ed25519 signature
  created_at       timestamptz not null default now()
);
create index on public.messages (conversation_id, created_at desc);

