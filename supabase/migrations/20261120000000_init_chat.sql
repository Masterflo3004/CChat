create function public.before_message_insert()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_conv public.conversations;
begin
  select * into v_conv from public.conversations where id = new.conversation_id;
  if v_conv.rotation_needed then
    raise exception 'conversation key must be rotated first' using errcode = '40001';
  end if;
  if new.key_epoch <> v_conv.current_epoch then
    raise exception 'message must use the current key epoch' using errcode = '40001';
  end if;
  new.created_at := now();
  return new;
end;
$$;

create trigger messages_before_insert
  before insert on public.messages
  for each row execute function public.before_message_insert();

create function public.after_message_insert()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
begin
  update public.conversations set last_message_at = new.created_at
  where id = new.conversation_id;
  update public.conversation_members set last_read_at = new.created_at
  where conversation_id = new.conversation_id and user_id = new.sender_id;
  return null;
end;
$$;

create trigger messages_after_insert
  after insert on public.messages
  for each row execute function public.after_message_insert();

