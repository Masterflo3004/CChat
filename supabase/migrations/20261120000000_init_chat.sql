-- profiles: everyone signed in can look people up; you can edit only yourself.
create policy "profiles readable" on public.profiles
  for select to authenticated using (true);
create policy "update own profile" on public.profiles
  for update to authenticated
  using (id = (select auth.uid())) with check (id = (select auth.uid()));

-- key_backups: owner only.
create policy "own key backup" on public.key_backups
  for all to authenticated
  using (user_id = (select auth.uid())) with check (user_id = (select auth.uid()));

-- skins & fonts: readable by everyone signed in (others must render them), owner writes.
create policy "skins readable" on public.message_skins
  for select to authenticated using (true);
create policy "manage own skins" on public.message_skins
  for insert to authenticated with check (owner_id = (select auth.uid()));
create policy "update own skins" on public.message_skins
  for update to authenticated
  using (owner_id = (select auth.uid())) with check (owner_id = (select auth.uid()));
create policy "delete own skins" on public.message_skins
  for delete to authenticated using (owner_id = (select auth.uid()));

create policy "fonts readable" on public.user_fonts
  for select to authenticated using (true);
create policy "manage own fonts" on public.user_fonts
  for insert to authenticated with check (owner_id = (select auth.uid()));
create policy "delete own fonts" on public.user_fonts
  for delete to authenticated using (owner_id = (select auth.uid()));

-- conversations: members read. All writes go through the RPCs above.
create policy "members read conversations" on public.conversations
  for select to authenticated using (public.is_member(id));

-- conversation_members: members see each other; you may only update your read marker.
create policy "members read members" on public.conversation_members
  for select to authenticated using (public.is_member(conversation_id));
create policy "update own read marker" on public.conversation_members
  for update to authenticated
  using (user_id = (select auth.uid())) with check (user_id = (select auth.uid()));
revoke insert, update, delete on public.conversation_members from authenticated, anon;
grant update (last_read_at) on public.conversation_members to authenticated;

-- conversation_keys: you can only read keys wrapped for you.
create policy "read own wrapped keys" on public.conversation_keys
  for select to authenticated using (recipient_id = (select auth.uid()));

-- messages: members read; members send as themselves; senders delete their own.
create policy "members read messages" on public.messages
  for select to authenticated using (public.is_member(conversation_id));
create policy "members send messages" on public.messages
  for insert to authenticated
  with check (sender_id = (select auth.uid()) and public.is_member(conversation_id));
create policy "delete own messages" on public.messages
  for delete to authenticated using (sender_id = (select auth.uid()));
revoke update on public.messages from authenticated, anon;

