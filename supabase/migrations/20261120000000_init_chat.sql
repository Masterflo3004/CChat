values
  -- encrypted blobs only: <conversation_id>/<uuid>.bin
  ('attachments', 'attachments', false, 10485760, array['application/octet-stream']),
  -- skin images: <owner_id>/<uuid>.<ext>
  ('skins', 'skins', false, 5242880, array['image/png', 'image/jpeg', 'image/webp', 'image/gif']),
  -- font files: <owner_id>/<uuid>.<ext>
  ('fonts', 'fonts', false, 2097152,
     array['font/ttf', 'font/otf', 'application/x-font-ttf', 'application/x-font-otf',
           'application/font-sfnt', 'application/octet-stream']);

create policy "members read attachments" on storage.objects
  for select to authenticated
  using (bucket_id = 'attachments' and public.is_member_of_folder((storage.foldername(name))[1]));
create policy "members upload attachments" on storage.objects
  for insert to authenticated
  with check (bucket_id = 'attachments' and public.is_member_of_folder((storage.foldername(name))[1]));

create policy "cosmetics readable" on storage.objects
  for select to authenticated
  using (bucket_id in ('skins', 'fonts'));
create policy "upload own cosmetics" on storage.objects
  for insert to authenticated
  with check (bucket_id in ('skins', 'fonts')
              and (storage.foldername(name))[1] = (select auth.uid())::text);
create policy "update own cosmetics" on storage.objects
  for update to authenticated
  using (bucket_id in ('skins', 'fonts')
         and (storage.foldername(name))[1] = (select auth.uid())::text);
create policy "delete own cosmetics" on storage.objects
  for delete to authenticated
  using (bucket_id in ('skins', 'fonts')
         and (storage.foldername(name))[1] = (select auth.uid())::text);
