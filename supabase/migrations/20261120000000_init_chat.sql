create function public.is_member(p_conversation_id uuid)
returns boolean
language sql
security definer
stable
set search_path = ''
as $$
  select exists (
    select 1 from public.conversation_members
    where conversation_id = p_conversation_id
      and user_id = (select auth.uid())
  );
$$;

create function public.is_admin(p_conversation_id uuid)
returns boolean
language sql
security definer
stable
set search_path = ''
as $$
  select exists (
    select 1 from public.conversation_members
    where conversation_id = p_conversation_id
      and user_id = (select auth.uid())
      and role = 'admin'
  );
$$;

-- Used by storage policies: first folder of the object path is the conversation id.
create function public.is_member_of_folder(p_folder text)
returns boolean
language sql
security definer
stable
set search_path = ''
as $$
  select case
    when p_folder ~* '^[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}$'
      then public.is_member(p_folder::uuid)
    else false
  end;
$$;

-- Creates the profile row for every new auth user.
create function public.handle_new_user()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_username text := lower(coalesce(new.raw_user_meta_data ->> 'username', ''));
begin
  if v_username !~ '^[a-z0-9_]{3,24}$' then
    v_username := 'user_' || substr(replace(new.id::text, '-', ''), 1, 12);
  elsif exists (select 1 from public.profiles where username = v_username) then
    v_username := left(v_username, 17) || '_' || substr(replace(new.id::text, '-', ''), 1, 6);
  end if;

  insert into public.profiles (id, username, display_name)
  values (new.id, v_username, nullif(new.raw_user_meta_data ->> 'display_name', ''));
  return new;
end;
$$;

create trigger on_auth_user_created
  after insert on auth.users
  for each row execute function public.handle_new_user();

-- Validates that p_wrapped_keys contains exactly one wrapped key for every current
-- member of the conversation and stores them under p_epoch.
create function public._store_epoch_keys(
  p_conversation_id uuid,
  p_epoch int,
  p_wrapped_keys jsonb
)
returns void
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_member_count int;
  v_key_count int;
  v_matching int;
begin
  if jsonb_typeof(p_wrapped_keys) is distinct from 'array' then
    raise exception 'wrapped keys must be a JSON array';
  end if;

  select count(*) into v_member_count
  from public.conversation_members where conversation_id = p_conversation_id;

  select count(distinct k.recipient_id) into v_key_count
  from jsonb_to_recordset(p_wrapped_keys) as k(recipient_id uuid, wrapped_key text);

  select count(distinct k.recipient_id) into v_matching
  from jsonb_to_recordset(p_wrapped_keys) as k(recipient_id uuid, wrapped_key text)
  join public.conversation_members m
    on m.conversation_id = p_conversation_id and m.user_id = k.recipient_id
  where k.wrapped_key is not null and char_length(k.wrapped_key) between 40 and 512;

  if v_key_count <> jsonb_array_length(p_wrapped_keys)
     or v_matching <> v_member_count
     or v_key_count <> v_member_count then
    raise exception 'wrapped keys must cover exactly the current members'
      using errcode = '22023';
  end if;

  insert into public.conversation_keys (conversation_id, epoch, recipient_id, sender_id, wrapped_key)
  select p_conversation_id, p_epoch, k.recipient_id, (select auth.uid()), k.wrapped_key
  from jsonb_to_recordset(p_wrapped_keys) as k(recipient_id uuid, wrapped_key text);

  update public.conversations
  set current_epoch = p_epoch, rotation_needed = false
  where id = p_conversation_id;
end;
$$;

