-- Creates a 1:1 chat (p_is_group = false, exactly one other member) or a group chat.
-- For 1:1 chats an existing conversation between the two users is returned instead.
create function public.create_conversation(
  p_conversation_id uuid,
  p_is_group boolean,
  p_name text,
  p_member_ids uuid[],
  p_wrapped_keys jsonb
)
returns uuid
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_uid uuid := (select auth.uid());
  v_members uuid[];
  v_dm_key text;
  v_existing uuid;
begin
  if v_uid is null then
    raise exception 'not authenticated' using errcode = '42501';
  end if;

  select array_agg(distinct m) into v_members
  from unnest(coalesce(p_member_ids, '{}') || v_uid) as m;

  if exists (
    select 1 from unnest(v_members) as m
    left join public.profiles p on p.id = m
    where p.id is null or p.x25519_public_key is null
  ) then
    raise exception 'all members must exist and have encryption keys' using errcode = '22023';
  end if;

  if p_is_group then
    if p_name is null or char_length(trim(p_name)) = 0 then
      raise exception 'group chats need a name' using errcode = '22023';
    end if;
    if cardinality(v_members) < 2 then
      raise exception 'a group needs at least one other member' using errcode = '22023';
    end if;
  else
    if cardinality(v_members) <> 2 then
      raise exception 'a direct chat has exactly two members' using errcode = '22023';
    end if;
    select least(v_members[1], v_members[2])::text || ':' || greatest(v_members[1], v_members[2])::text
      into v_dm_key;
    select id into v_existing from public.conversations where dm_key = v_dm_key;
    if v_existing is not null then
      return v_existing;
    end if;
  end if;

  insert into public.conversations (id, is_group, name, created_by, dm_key, current_epoch)
  values (p_conversation_id, p_is_group, case when p_is_group then trim(p_name) end,
          v_uid, v_dm_key, 1);

  insert into public.conversation_members (conversation_id, user_id, role)
  select p_conversation_id, m, case when m = v_uid or not p_is_group then 'admin' else 'member' end
  from unnest(v_members) as m;

  perform public._store_epoch_keys(p_conversation_id, 1, p_wrapped_keys);
  return p_conversation_id;
end;
$$;

-- Starts a new key epoch for the current members. Any member may do this
-- (required after someone leaves, see rotation_needed).
create function public.rotate_conversation_key(
  p_conversation_id uuid,
  p_epoch int,
  p_wrapped_keys jsonb
)
returns void
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_current int;
begin
  if not public.is_member(p_conversation_id) then
    raise exception 'not a member' using errcode = '42501';
  end if;
  select current_epoch into v_current from public.conversations
  where id = p_conversation_id for update;
  if p_epoch <> v_current + 1 then
    raise exception 'stale epoch' using errcode = '40001';
  end if;
  perform public._store_epoch_keys(p_conversation_id, p_epoch, p_wrapped_keys);
end;
$$;

-- Adds members to a group and rotates the key in the same transaction.
-- p_wrapped_keys must cover old AND new members.
create function public.add_group_members(
  p_conversation_id uuid,
  p_user_ids uuid[],
  p_epoch int,
  p_wrapped_keys jsonb
)
returns void
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_current int;
begin
  if not public.is_admin(p_conversation_id) then
    raise exception 'only admins can add members' using errcode = '42501';
  end if;
  select current_epoch into v_current from public.conversations
  where id = p_conversation_id and is_group for update;
  if v_current is null then
    raise exception 'not a group chat' using errcode = '22023';
  end if;
  if p_epoch <> v_current + 1 then
    raise exception 'stale epoch' using errcode = '40001';
  end if;
  if exists (
    select 1 from unnest(p_user_ids) as m
    left join public.profiles p on p.id = m
    where p.id is null or p.x25519_public_key is null
  ) then
    raise exception 'all members must exist and have encryption keys' using errcode = '22023';
  end if;

  insert into public.conversation_members (conversation_id, user_id)
  select p_conversation_id, m from unnest(p_user_ids) as m
  on conflict do nothing;

  perform public._store_epoch_keys(p_conversation_id, p_epoch, p_wrapped_keys);
end;
$$;

-- Removes a member (admin only) and rotates the key in the same transaction.
-- p_wrapped_keys must cover the remaining members.
create function public.remove_group_member(
  p_conversation_id uuid,
  p_user_id uuid,
  p_epoch int,
  p_wrapped_keys jsonb
)
returns void
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_current int;
begin
  if not public.is_admin(p_conversation_id) then
    raise exception 'only admins can remove members' using errcode = '42501';
  end if;
  if p_user_id = (select auth.uid()) then
    raise exception 'use leave_conversation to leave' using errcode = '22023';
  end if;
  select current_epoch into v_current from public.conversations
  where id = p_conversation_id and is_group for update;
  if v_current is null then
    raise exception 'not a group chat' using errcode = '22023';
  end if;
  if p_epoch <> v_current + 1 then
    raise exception 'stale epoch' using errcode = '40001';
  end if;

  delete from public.conversation_members
  where conversation_id = p_conversation_id and user_id = p_user_id;

  perform public._store_epoch_keys(p_conversation_id, p_epoch, p_wrapped_keys);
end;
$$;

-- Leaves a group. The leaver still knows the current key, so the conversation is
-- flagged and the next remaining member to send a message rotates the key first.
create function public.leave_conversation(p_conversation_id uuid)
returns void
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_uid uuid := (select auth.uid());
begin
  if not exists (select 1 from public.conversations where id = p_conversation_id and is_group) then
    raise exception 'only group chats can be left' using errcode = '22023';
  end if;
  if not public.is_member(p_conversation_id) then
    raise exception 'not a member' using errcode = '42501';
  end if;

  delete from public.conversation_members
  where conversation_id = p_conversation_id and user_id = v_uid;

  if not exists (select 1 from public.conversation_members where conversation_id = p_conversation_id) then
    delete from public.conversations where id = p_conversation_id;
    return;
  end if;

  -- Make sure the group keeps an admin.
  if not exists (
    select 1 from public.conversation_members
    where conversation_id = p_conversation_id and role = 'admin'
  ) then
    update public.conversation_members set role = 'admin'
    where (conversation_id, user_id) = (
      select conversation_id, user_id from public.conversation_members
      where conversation_id = p_conversation_id
      order by joined_at limit 1
    );
  end if;

  update public.conversations set rotation_needed = true where id = p_conversation_id;
end;
$$;

-- Conversation list for the current user, newest activity first.
create function public.my_conversations()
returns table (
  id uuid,
  is_group boolean,
  name text,
  current_epoch int,
  rotation_needed boolean,
  last_message_at timestamptz,
  created_at timestamptz,
  my_role text,
  last_read_at timestamptz,
  unread_count bigint,
  members jsonb
)
language sql
security definer
stable
set search_path = ''
as $$
  select
    c.id, c.is_group, c.name, c.current_epoch, c.rotation_needed,
    c.last_message_at, c.created_at, me.role, me.last_read_at,
    (select count(*) from public.messages msg
       where msg.conversation_id = c.id
         and msg.sender_id <> me.user_id
         and (me.last_read_at is null or msg.created_at > me.last_read_at)) as unread_count,
    (select jsonb_agg(jsonb_build_object(
              'id', p.id, 'username', p.username, 'display_name', p.display_name,
              'role', m.role) order by m.joined_at)
       from public.conversation_members m
       join public.profiles p on p.id = m.user_id
       where m.conversation_id = c.id) as members
  from public.conversation_members me
  join public.conversations c on c.id = me.conversation_id
  where me.user_id = (select auth.uid())
  order by coalesce(c.last_message_at, c.created_at) desc;
$$;

